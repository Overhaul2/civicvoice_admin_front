export default function Sidebar() {
  const { logout } = useAuth();
  const navigate = useNavigate();
  const cfg = routesConfig.citoyen;

  function handleLogout() {
    logout();
    navigate('/');
  }

  // Construire la liste des items visibles
  const navItems = Object.entries(cfg).filter(([, v]) => v.enabled);

  return (
    <aside className="cv-sidebar">
      <div className="cv-sidebar__logo">
        <div className="cv-sidebar__logo-icon">CV</div>
        <div>
          <div className="cv-sidebar__logo-text">CIVIC VOTE</div>
          <div className="cv-sidebar__logo-sub">Mali</div>
        </div>
      </div>

      <nav className="cv-sidebar__nav">
        {navItems.map(([key, item]) => (
          <NavLink
            key={key}
            to={item.path}
            className={({ isActive }) => 'cv-sidebar__item' + (isActive ? ' active' : '')}
          >
            <span className="cv-sidebar__icon">{icons[item.icon]}</span>
            {item.label}
          </NavLink>
        ))}
      </nav>

      <div className="cv-sidebar__logout">
        <button className="cv-sidebar__logout-btn" onClick={handleLogout}>
          <span className="cv-sidebar__icon">{icons.logout}</span>
          Déconnexion
        </button>
      </div>
    </aside>
  );
}